const auditPath=name=>'audit/'+(process.env.FITAPP_AUDIT_PREFIX?process.env.FITAPP_AUDIT_PREFIX+'-':'')+name;
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const server=require('../scripts/serve.cjs');
const fake=require('./fixtures/firebase.cjs');
(async()=>{
    await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
    let browser;const checks=[],errors=[];
    try{
        browser=await chromium.launch({channel:'msedge',headless:true});
        const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block',reducedMotion:'reduce'});
        await context.route('**/vendor/firebase-*.js',route=>route.fulfill({contentType:'text/javascript',body:route.request().url().endsWith('firebase-app.js')?fake:''}));
        const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.accept());
        await page.goto('http://127.0.0.1:'+server.address().port);await page.waitForFunction(()=>window.FitStore?.get('fitapp_cloud_base'));
        await page.evaluate(()=>{FitApp.openForgeModal();FitApp.generateForgedWorkout();});
        assert.match(await page.locator('.model-coverage').first().textContent(),/conjunto A \+ B \+ C/);
        assert.match(await page.locator('.model-coverage').first().textContent(),/elevação pélvica: Complemento desativado/);
        await page.click('#saveAndTrainButton');
        await page.locator('.rp-val').first().fill('10');await page.locator('.chk-set').first().check();
        await page.evaluate(()=>FitApp.adjustRestTime(150));
        const planBefore=await page.evaluate(()=>FitStore.get('fitapp_campaign_data'));
        await page.reload();await page.waitForFunction(async()=>(await import('/js/state.js')).state.isWorkoutActive);
        assert.equal(await page.evaluate(()=>JSON.parse(FitStore.get('fitapp_active_state')).version),4);
        assert.equal(await page.evaluate(()=>JSON.parse(FitStore.get('fitapp_active_state')).sessionPlanned[0].exercises[0].sets),3);
        await page.evaluate(async()=>{const {state}=await import('/js/state.js');state.currentRoutine[0].exercises[0].sets=4;FitApp.renderCurrentRoutine();FitApp.saveWorkoutState();});
        await page.evaluate(()=>{window.originalQueue=FitStore.updateQueue;FitStore.updateQueue=async()=>{throw new Error('simulated failure');};});
        await page.click('#btnFinishAction');
        assert.equal(await page.evaluate(async()=>(await import('/js/state.js')).state.isWorkoutActive),true);
        await page.evaluate(()=>{FitStore.updateQueue=window.originalQueue;});
        await context.setOffline(true);await page.click('#btnFinishAction');
        await page.waitForFunction(()=>document.getElementById('sessionSummary').open);
        const log=await page.evaluate(()=>JSON.parse(FitStore.get('fitapp_sync_queue')).at(-1));
        assert.equal(log.complete,false);assert.equal(JSON.parse(log.trainingContext).planned[0].exercises[0].sets,3);
        assert.equal(JSON.parse(log.trainingContext).execution[0].exercises[0].sets,4);
        assert.equal(JSON.parse(log.trainingContext).execution[0].restSeconds,150);
        assert.equal(await page.evaluate(()=>FitStore.get('fitapp_campaign_data')),planBefore);
        await page.evaluate(()=>document.getElementById('sessionSummary').close());await page.click('#nav-evolucao');
        assert.match(await page.locator('#trainingTracking').textContent(),/1 de 3 registros previstos · 2 não realizados/);
        assert.match(await page.locator('#trainingTracking').textContent(),/Treino B · sem registro/);
        checks.push('proposta por modelo, planejamento recuperado, parcial offline, falha durável e ficha preservada');
        await context.setOffline(false);
        await page.evaluate(()=>FitApp.openHistoryModal());
        assert.equal(await page.locator('#historyListView .history-completion').first().textContent(),'Parcial');
        await page.evaluate(()=>document.getElementById('historyModal').style.display='none');
        await page.click('#nav-treino');await page.click('#quickWorkoutOpen');
        const side=await page.evaluate(async()=>{const {state}=await import('/js/state.js');return state.currentRoutine.findIndex(block=>block.exercises.some(ex=>ex.sideMode==='alternating'));});
        await page.locator(`#rp_set_${side}_0_1`).fill('21');await page.locator(`#chk_set_${side}_0_1`).check();
        await page.locator(`#rp_set_${side}_0_2`).fill('27');await page.locator(`#chk_set_${side}_0_2`).check();
        await page.click('#btnFinishAction');await page.waitForFunction(()=>document.getElementById('sessionSummary').open);
        await page.evaluate(()=>document.getElementById('sessionSummary').close());
        await page.evaluate(()=>FitApp.openHistoryModal());
        assert.match(await page.locator('#historyListView').textContent(),/E1: 0 kg · 21 s/);
        assert.match(await page.locator('#historyListView').textContent(),/D1: 0 kg · 27 s/);
        await page.evaluate(()=>document.getElementById('historyModal').style.display='none');
        checks.push('histórico distingue parcial, segundos e os dois lados da prancha');
        await page.click('#nav-evolucao');
        for(const [scheme,width,height] of [['light',390,844],['dark',1280,900]]){
            await page.emulateMedia({colorScheme:scheme});await page.setViewportSize({width,height});
            await page.waitForFunction(()=>!document.getElementById('toast').classList.contains('show'));
            await page.evaluate(()=>{document.querySelectorAll('#trainingTracking details').forEach(item=>item.open=false);document.getElementById('trainingTracking').scrollIntoView();scrollBy(0,-80);});
            await page.screenshot({path:`audit/tracking-${scheme}.png`});
            assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
        }
        await page.evaluate(()=>{const logs=JSON.parse(FitStore.get('fitapp_week_log'));logs.push({_id:'legacy',date:'2026-10-01',tipo:'Livre',complete:true,data:[{exercise:'Supino',set:1,kg:20,reps:10}]});FitStore.set('fitapp_week_log',JSON.stringify(logs));FitApp.renderHistoryList();});
        assert.match(await page.locator('#historyListView').textContent(),/Planejamento inicial indisponível/);
        await page.evaluate(()=>{
            const routine=structuredClone(JSON.parse(FitStore.get('fitapp_campaign_data')).workouts.A);
            routine[0].exercises[0].setsData=[{checked:true,kg:10,reps:8}];
            FitStore.set('fitapp_active_state',JSON.stringify({version:3,userId:FitStore.uid,sessionId:'legacy-active',currentWorkoutType:'Livre',currentRoutine:routine,workoutStartTime:Date.now()-180000,restSeconds:90}));
        });
        await page.reload();await page.waitForFunction(async()=>(await import('/js/state.js')).state.isWorkoutActive);
        assert.equal(await page.evaluate(async()=>(await import('/js/state.js')).state.sessionPlanned),null);
        await page.click('#btnFinishAction');await page.waitForFunction(()=>document.getElementById('sessionSummary').open);
        assert.equal(await page.evaluate(()=>JSON.parse(JSON.parse(FitStore.get('fitapp_week_log')).find(log=>log._id==='legacy-active').trainingContext).planned),null);
        await page.evaluate(()=>document.getElementById('sessionSummary').close());
        const future=await page.evaluate(()=>{const value=JSON.stringify({version:99,userId:FitStore.uid,currentWorkoutType:'A',currentRoutine:[]});FitStore.set('fitapp_active_state',value);return value;});
        await page.reload();await page.waitForFunction(()=>window.FitStore?.get('fitapp_cloud_base'));
        assert.equal(await page.evaluate(()=>FitStore.get('fitapp_active_state')),future);
        assert.equal(await page.evaluate(async()=>(await import('/js/state.js')).state.isWorkoutActive),false);
        checks.push('sessão ativa antiga recuperada sem previsão inventada; versão futura preservada sem executar');
        await page.evaluate(()=>{FitStore.bindUser('another-user');FitApp.renderMetricsChart();});
        assert.doesNotMatch(await page.locator('#trainingTracking').textContent(),/1 de 3 registros|Supino Inclinado/);
        checks.push('temas, celular sem transbordamento, legado sem inferência e separação entre contas');
        assert.deepEqual(errors,[]);
        fs.writeFileSync(auditPath('training-tracking-browser-validation.json'),JSON.stringify({date:new Date().toISOString(),mode:'Firebase simulado; dados de teste locais',physicalDevices:false,checks,errors},null,2)+'\n');
        console.log(JSON.stringify({passed:checks.length,checks,errors}));
    }finally{if(browser)await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
