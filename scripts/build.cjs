const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const vm=require('node:vm');
const cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const resolve=p=>path.join(root,p);
const aiPolicy=JSON.parse(fs.readFileSync(resolve('functions/ai-policy.json'),'utf8'));
fs.writeFileSync(resolve('public/js/ai-policy.js'),'// Generated by scripts/build.cjs from functions/ai-policy.json.\nglobalThis.FitAIPolicy=Object.freeze('+JSON.stringify(aiPolicy)+');\n');
fs.mkdirSync(resolve('public/vendor'),{recursive:true});
for(const [source,name] of [
    ['firebase/firebase-app-compat.js','firebase-app.js'],
    ['firebase/firebase-auth-compat.js','firebase-auth.js'],
    ['firebase/firebase-firestore-compat.js','firebase-firestore.js'],
    ['chart.js/dist/chart.umd.js','chart.js'],
    ['html2canvas/dist/html2canvas.min.js','html2canvas.js']
])fs.copyFileSync(resolve('node_modules/'+source),resolve('public/vendor/'+name));
const ctx=vm.createContext({window:{}});
vm.runInContext(fs.readFileSync(resolve('public/js/dados.js'),'utf8'),ctx);
fs.writeFileSync(resolve('functions/catalogue.json'),JSON.stringify({exercises:ctx.window.dictionaryData,stickers:ctx.window.stickersDB},null,2)+'\n');
// Gera o manifesto pelo próprio SDK. Também evita problemas de descoberta via
// wrappers .cmd quando o projeto fica em um caminho Windows com espaços.
const manifest=cp.spawnSync(process.execPath,[resolve('functions/node_modules/firebase-functions/lib/bin/firebase-functions.js')],{
    cwd:resolve('functions'),env:{...process.env,FUNCTIONS_MANIFEST_OUTPUT_PATH:resolve('functions/functions.yaml')},encoding:'utf8'
});
if(manifest.status!==0)throw new Error('Não foi possível gerar o manifesto das funções: '+manifest.stderr);
const files=['/','/index.html','/manifest.json','/icon-192.png','/icon-512.png','/icon.svg',...fs.readdirSync(resolve('public/css')).filter(f=>f.endsWith('.css')).map(f=>'/css/'+f),...fs.readdirSync(resolve('public/fonts')).filter(f=>f.endsWith('.ttf')).map(f=>'/fonts/'+f),...fs.readdirSync(resolve('public/js')).filter(f=>f.endsWith('.js')&&f!=='admin.js').map(f=>'/js/'+f),...fs.readdirSync(resolve('public/vendor')).filter(f=>f.endsWith('.js')).map(f=>'/vendor/'+f)];
const hash=crypto.createHash('sha256');
hash.update(fs.readFileSync(__filename));
for(const file of files)hash.update(fs.readFileSync(resolve('public'+(file==='/'?'/index.html':file))));
const version=hash.digest('hex').slice(0,16);
const worker=`const CACHE = 'fitapp-${version}';
const ASSETS = ${JSON.stringify(files)};
self.addEventListener('install', event => event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS.map(url => new Request(url, {cache:'reload'}))))));
self.addEventListener('activate', event => event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('fitapp-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim())));
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || url.pathname.includes('admin')) return;
  if (!ASSETS.includes(url.pathname) && event.request.mode !== 'navigate') return;
  event.respondWith(caches.open(CACHE).then(async cache => {
    const cached = await cache.match(event.request, {ignoreSearch:true});
    if (cached) return cached;
    try { return await fetch(event.request); }
    catch (error) { if(event.request.mode==='navigate') return cache.match('/index.html'); throw error; }
  }));
});
`;
fs.writeFileSync(resolve('public/sw.js'),worker);
fs.writeFileSync(resolve('public/version.json'),JSON.stringify({version})+'\n');
console.log('Build FitApp:',version);
